-- Drop tables in reverse order of dependencies to avoid FK violation during resets
DROP TABLE IF EXISTS REPORT_RUN_LOG;
DROP TABLE IF EXISTS REPORT_SCHEDULE_MASTER;
DROP TABLE IF EXISTS REPORT_MASTER;
DROP TABLE IF EXISTS TENANT_MASTER;

-- 1. TENANT MASTER
CREATE TABLE TENANT_MASTER (
    TENANT_ID VARCHAR(50) PRIMARY KEY,
    TENANT_NAME VARCHAR(100) NOT NULL,
    TENANT_TIER VARCHAR(20) NOT NULL CHECK (TENANT_TIER IN ('Tier 1', 'Tier 2')),
    TENANT_PRIMARY_CONTACT VARCHAR(100),
    TENANT_PRIMARY_EMAIL VARCHAR(100)
);

-- 2. REPORT MASTER
CREATE TABLE REPORT_MASTER (
    REP_ID VARCHAR(50) PRIMARY KEY,
    TENANT_ID VARCHAR(50) NOT NULL,
    REP_NAME VARCHAR(100) NOT NULL,
    REP_CRITICALITY_CATEGORY VARCHAR(20) NOT NULL CHECK (REP_CRITICALITY_CATEGORY IN ('Critical', 'High', 'Medium', 'Low')),
    FOREIGN KEY (TENANT_ID) REFERENCES TENANT_MASTER(TENANT_ID)
);

-- 3. REPORT SCHEDULE MASTER
CREATE TABLE REPORT_SCHEDULE_MASTER (
    REP_SCHE_ID VARCHAR(50) PRIMARY KEY,
    REP_ID VARCHAR(50) NOT NULL,
    REP_SCHE_FREQUENCY VARCHAR(50) NOT NULL,
    REP_SCHE_TRIGGER_TIME TIME NOT NULL,
    REP_SCHE_RETRY_ATTEMPTS INT NOT NULL CHECK (REP_SCHE_RETRY_ATTEMPTS BETWEEN 0 AND 3),
    REP_SCHE_TIMEOUT_SECONDS INT NOT NULL,
    FOREIGN KEY (REP_ID) REFERENCES REPORT_MASTER(REP_ID)
);

-- 4. REPORT RUN LOG
CREATE TABLE REPORT_RUN_LOG (
    RR_ID VARCHAR(50) PRIMARY KEY,
    REP_ID VARCHAR(50) NOT NULL,
    REP_SCHE_ID VARCHAR(50) NOT NULL,
    RR_SCHEDULED_AT DATETIME NOT NULL,
    RR_STATUS VARCHAR(30) NOT NULL, 
    RR_ATTEMPT_NUMBER INT NOT NULL,
    RR_DURATION_SECONDS INT,
    RR_ROW_COUNT INT,
    RR_FAILURE_CATEGORY VARCHAR(50), 
    RR_IS_AUTO_RETRY BOOLEAN DEFAULT 0,
    FOREIGN KEY (REP_ID) REFERENCES REPORT_MASTER(REP_ID),
    FOREIGN KEY (REP_SCHE_ID) REFERENCES REPORT_SCHEDULE_MASTER(REP_SCHE_ID)
);

-- 5. Notification 
CREATE TABLE NOTIFICATION_LOG (
    NOTIF_ID VARCHAR(50) PRIMARY KEY,
    RR_ID VARCHAR(50) NOT NULL,
    TENANT_ID VARCHAR(50) NOT NULL,
    NOTIF_TYPE VARCHAR(20) NOT NULL, -- 'SUCCESS', 'FAILURE'
    CHANNELS_USED VARCHAR(50) NOT NULL, -- 'EMAIL', 'EMAIL+SMS'
    RECIPIENTS TEXT NOT NULL,
    MESSAGE_BODY TEXT NOT NULL,
    SENT_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (RR_ID) REFERENCES REPORT_RUN_LOG(RR_ID),
    FOREIGN KEY (TENANT_ID) REFERENCES TENANT_MASTER(TENANT_ID)
);